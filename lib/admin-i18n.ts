export function translateAdmin(
  locale: AdminLocale,
  key: string,
  vars?: Record<string, string | number>
): string {
  let s = adminMessages[locale][key] ?? adminMessages.fr[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{{${k}}}`).join(String(v))
    }
  }
  return s
}

export function adminOrderStatusLabel(locale: AdminLocale, status: string): string {
  return translateAdmin(locale, `status.${status}`)
}
